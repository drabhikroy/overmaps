import time, os
from playwright.sync_api import sync_playwright
os.makedirs("tests/shots", exist_ok=True)
def ok(name, cond, extra=""): print(("PASS " if cond else "FAIL ") + name, str(extra)[:220], flush=True)
def wait_for(pg, fn, t=60):
    t0 = time.time()
    while time.time() - t0 < t:
        try:
            if fn(): return True
        except Exception: pass
        time.sleep(0.4)
    return False
def src(pg, sel): return pg.evaluate("(sel) => (document.querySelector(sel + ' img')||{}).src || ''", sel)
with sync_playwright() as p:
    b = p.chromium.launch(headless=True, args=["--no-sandbox"])
    ctx = b.new_context(viewport={"width": 1440, "height": 900}, accept_downloads=True); pg = ctx.new_page()
    errs = []; pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None); pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("http://127.0.0.1:8765/"); pg.wait_for_selector("#find", timeout=60000); time.sleep(2)
    # suggestions while typing (stubbed service): an address-looking text lists addresses
    pg.fill("#query", "401 dav"); ok("address suggestions list appears", wait_for(pg, lambda: pg.locator("#place_sugg .sugg-item").count() >= 1, 15), pg.locator("#place_sugg .sugg-item").all_inner_texts())
    main_swatches = pg.locator("#sb .style-picker label").count()
    main_cols = pg.evaluate("getComputedStyle(document.querySelector('#sb .style-picker .shiny-options-group')).gridTemplateColumns.split(' ').length")
    pg.click("#history_open"); pg.wait_for_selector("#h_view", timeout=20000)
    ok("title is capitalized as asked", wait_for(pg, lambda: pg.inner_text("#shiny-modal .modal-title").strip() == "Explore history: The roads of the Roman Empire", 10), pg.inner_text("#shiny-modal .modal-title"))
    heads = pg.locator("#shiny-modal .ctl-head").all_inner_texts()
    ok("window uses the same numbered section headings", any("Choose a look" in h for h in heads) and any("Choose a map type" in h for h in heads), heads)
    m_swatches = pg.locator("#shiny-modal .tab-pane.active .style-picker label").count()
    m_cols = pg.evaluate("getComputedStyle(document.querySelector('#shiny-modal .tab-pane.active .style-picker .shiny-options-group')).gridTemplateColumns.split(' ').length")
    ok("look picker matches the main page (swatches and grid)", m_swatches == main_swatches and m_swatches >= 4 and m_cols == main_cols == 3, (m_swatches, main_swatches, m_cols, main_cols))
    ok("map type cards use the main page cards", pg.locator("#shiny-modal .tab-pane.active .view-picker .vt").count() == 4 and pg.locator("#shiny-modal .tab-pane.active .view-picker .vb").count() == 4)
    ok("map draws", wait_for(pg, lambda: src(pg, "#h_map") != "", 60)); time.sleep(1.5)
    d0 = pg.evaluate("(() => { const r = document.querySelector('#shiny-modal .modal-dialog').getBoundingClientRect(); return [r.width, r.height]; })()")
    i0 = pg.evaluate("(() => { const r = document.querySelector('#h_map img').getBoundingClientRect(); return [r.width, r.height]; })()")
    pg.screenshot(path="tests/shots/history_normal.png")
    pg.click("#h-full-btn"); time.sleep(1.2)
    d1 = pg.evaluate("(() => { const r = document.querySelector('#shiny-modal .modal-dialog').getBoundingClientRect(); return [r.width, r.height]; })()")
    i1 = pg.evaluate("(() => { const r = document.querySelector('#h_map img').getBoundingClientRect(); return [r.width, r.height]; })()")
    ok("full screen fills the window", d1[0] >= 1430 and d1[1] >= 890 and d0[0] < 1300, (d0, d1))
    ok("full screen button reads Exit and is pressed", pg.get_attribute("#h-full-btn", "aria-pressed") == "true" and pg.is_visible("#h-full-btn .when-expanded") and not pg.is_visible("#h-full-btn .when-normal"))
    ok("map is much larger in full screen", i1[0] > i0[0] * 1.4, (i0, i1))
    sb = pg.evaluate("(() => { const l = document.querySelector('#shiny-modal .tab-pane.active .bslib-sidebar-layout'); const sbe = l.querySelector(':scope > .sidebar'); const m = l.querySelector(':scope > .main'); return [sbe.getBoundingClientRect().width, m.getBoundingClientRect().width, !!l.querySelector('.bslib-sidebar-resize-handle, .sidebar-resize-handle, [class*=resize]'), !!l.querySelector('.collapse-toggle')]; })()")
    ok("full screen keeps the sidebar at its normal width", 330 <= sb[0] <= 400 and sb[1] > 900, sb)
    ok("sidebar has a resize handle and a collapse button like the main page", sb[2] and sb[3], sb)
    pg.click("#shiny-modal .tab-pane.active .collapse-toggle"); time.sleep(0.9)
    sb2 = pg.evaluate("(() => { const l = document.querySelector('#shiny-modal .tab-pane.active .bslib-sidebar-layout'); return [l.querySelector(':scope > .main').getBoundingClientRect().width, l.getAttribute('data-bslib-sidebar-open') || l.className]; })()")
    ok("sidebar collapses so the map gets the room", sb2[0] > sb[1] + 250, sb2)
    pg.click("#shiny-modal .tab-pane.active .collapse-toggle"); time.sleep(0.9)
    pg.screenshot(path="tests/shots/history_full.png")
    pg.click("#h-full-btn"); time.sleep(0.8)
    d2 = pg.evaluate("(() => { const r = document.querySelector('#shiny-modal .modal-dialog').getBoundingClientRect(); return [r.width, r.height]; })()")
    ok("second click returns to the normal size", d2[0] < 1300 and pg.get_attribute("#h-full-btn", "aria-pressed") == "false", d2)
    # Roman look change uses the radio swatches
    s0 = src(pg, "#h_map"); pg.click("#shiny-modal label:has(input[name=h_style][value=dusk])"); ok("look change redraws", wait_for(pg, lambda: src(pg, "#h_map") not in ("", s0), 60))
    # ancient cities tab
    pg.click("#shiny-modal a[data-value=cities]"); time.sleep(1)
    ok("title follows the tab", pg.inner_text("#shiny-modal .modal-title").strip() == "Explore history: Streets of ancient cities", pg.inner_text("#shiny-modal .modal-title"))
    ok("city tab has the same pickers", pg.locator("#shiny-modal .tab-pane.active .style-picker label").count() == main_swatches and pg.locator("#shiny-modal .tab-pane.active .view-picker .vt").count() == 3)
    ok("no download button before a map", not pg.is_visible("#c_download"))
    ok("note under the city", "Roman" in pg.inner_text("#c_note"), pg.inner_text("#c_note"))
    pg.select_option("#c_site", "pompeii"); pg.click("#c_draw")
    ok("city map draws", wait_for(pg, lambda: src(pg, "#c_map") != "", 90)); time.sleep(1.5)
    st = pg.inner_text("#c_status"); ok("coverage is reported", "mapped streets and paths" in st, st)
    pg.screenshot(path="tests/shots/city_pompeii.png")
    c0 = src(pg, "#c_map"); pg.click("#shiny-modal .tab-pane.active label:has(input[name=c_view][value=blocks])")
    ok("map type change redraws without a new download", wait_for(pg, lambda: src(pg, "#c_map") not in ("", c0), 60))
    pg.click("#shiny-modal .tab-pane.active label:has(input[name=c_style][value=dusk])"); time.sleep(4); pg.screenshot(path="tests/shots/city_dusk.png")
    pg.select_option("#c_site", "angkor_thom"); time.sleep(0.8)
    ok("changing city says the map is stale", "Press Draw map" in pg.inner_text("#c_status"), pg.inner_text("#c_status"))
    ok("download enabled", pg.is_visible("#c_download"))
    with pg.expect_download(timeout=90000) as dl: pg.click("#c_download")
    d = dl.value; path = "tests/shots/city_download.png"; d.save_as(path)
    ok("download is a PNG named for the city", d.suggested_filename.startswith("streets_pompeii_blocks_") and open(path, "rb").read(4) == b"\x89PNG", d.suggested_filename)
    pg.click("#h-full-btn"); time.sleep(1.2); pg.screenshot(path="tests/shots/city_full.png")
    pg.keyboard.press("Escape"); time.sleep(1.2)
    ok("window closes and the next open starts at normal size", not pg.is_visible("#h_tab"))
    pg.click("#history_open"); pg.wait_for_selector("#h_view", timeout=20000); time.sleep(1)
    d3 = pg.evaluate("(() => document.querySelector('#shiny-modal .modal-dialog').getBoundingClientRect().width)()")
    ok("reopened window is not stuck in full screen", d3 < 1300, d3)
    bad = [e for e in errs if "favicon" not in e and "Failed to load resource" not in e]
    ok("no console errors", not bad, bad)
    b.close()
