import time, os
from playwright.sync_api import sync_playwright
os.makedirs("tests/shots", exist_ok=True)
def ok(name, cond, extra=""): print(("PASS " if cond else "FAIL ") + name, str(extra)[:200], flush=True)
with sync_playwright() as p:
    b = p.chromium.launch(headless=True, args=["--no-sandbox"])
    ctx = b.new_context(viewport={"width": 1440, "height": 900}); pg = ctx.new_page()
    errs = []; pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None); pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("http://127.0.0.1:8765/"); pg.wait_for_selector("#find", timeout=60000); time.sleep(2)
    pg.screenshot(path="tests/shots/empty.png")
    ok("no color vision control", pg.query_selector("#cvd") is None)
    ok("watermark background set on empty map", "svg" in pg.evaluate("getComputedStyle(document.querySelector('#map')).backgroundImage"))
    ok("no place card before a place is chosen", pg.query_selector(".place-card") is None)
    ok("address switch hidden before a place is chosen", not pg.is_visible("#use_addr"))
    pg.click("#query"); pg.keyboard.type("elk", delay=80); time.sleep(2.0)
    items = pg.query_selector_all(".sugg-item[data-kind=place]"); ok("suggestions appear", len(items) >= 2, len(items))
    pg.screenshot(path="tests/shots/suggestions.png")
    items[0].click(); time.sleep(0.2)
    ok("list closes at once on click", len(pg.query_selector_all(".sugg-item[data-kind=place]")) == 0)
    time.sleep(3.0)
    ok("list stays closed after the lookup", len(pg.query_selector_all(".sugg-item[data-kind=place]")) == 0)
    pg.wait_for_selector(".place-card", timeout=20000); ok("place card shows the chosen place", "Elkins" in pg.inner_text(".place-card"), pg.inner_text(".place-card"))
    ok("no match list for a clicked suggestion", pg.query_selector("#choice") is None)
    ok("address switch appears once a place is chosen", pg.is_visible("#use_addr"))
    # quick click right after typing: the pending pause must not bring the list back
    pg.fill("#query", ""); pg.click("#query"); pg.keyboard.type("elk", delay=60); time.sleep(1.8)
    items = pg.query_selector_all(".sugg-item[data-kind=place]")
    pg.keyboard.type("i", delay=10); items = pg.query_selector_all(".sugg-item[data-kind=place]")
    if items: items[0].click()
    time.sleep(4.0); ok("list stays closed after a quick pick", len(pg.query_selector_all(".sugg-item[data-kind=place]")) == 0)
    pg.screenshot(path="tests/shots/chosen.png")
    # typed name then Find: several matches
    pg.fill("#query", "Elkins"); pg.click("#find"); time.sleep(3)
    ok("Find shows the chosen place", pg.query_selector(".place-card") is not None)
    ok("no suggestion list after Find", len(pg.query_selector_all(".sugg-item")) == 0)
    pg.click("#draw"); pg.wait_for_selector("#map img", timeout=90000); time.sleep(3)
    pg.screenshot(path="tests/shots/drawn.png", full_page=True)
    ok("map drawn", pg.is_visible("#map img"))
    sb = pg.query_selector("#sb, .sidebar"); sb.scroll_into_view_if_needed()
    pg.evaluate("document.querySelector('.sidebar-content, .sidebar').scrollTo(0, 99999)"); time.sleep(0.5)
    pg.screenshot(path="tests/shots/sidebar_bottom.png")
    ok("no browser errors", len(errs) == 0, errs)
    b.close()
